class EPKEngine:
    def generate_html(self, artist: str, genre: str, bio: str, spotify: str = "",
                      soundcloud: str = "", apple_music: str = "", youtube: str = "",
                      press_quotes: str = "", photo_url: str = "",
                      website: str = "", instagram: str = "", facebook: str = "",
                      twitter: str = "", contact_email: str = "", phone: str = "",
                      email: str = "") -> str:
        contact_email = contact_email or email or ""
        links_html = ""
        for label, url in [("Spotify", spotify), ("SoundCloud", soundcloud),
                           ("Apple Music", apple_music), ("YouTube", youtube),
                           ("Website", website), ("Instagram", instagram),
                           ("Facebook", facebook), ("Twitter", twitter)]:
            if url:
                links_html += f'<a href="{url}" style="display:inline-block;margin:4px 8px 4px 0;padding:6px 14px;background:#1a1a2e;color:#e0e0e0;text-decoration:none;border-radius:4px;font-size:13px">{label}</a>'

        press_html = ""
        if press_quotes:
            for q in press_quotes.split("\n"):
                q = q.strip()
                if q:
                    press_html += f'<blockquote style="border-left:3px solid #00d4ff;margin:8px 0;padding:4px 12px;color:#b0b0b0;font-style:italic">"{q}"</blockquote>'

        photo_html = ""
        if photo_url:
            photo_html = f'<img src="{photo_url}" style="max-width:300px;border-radius:8px;margin:12px 0" alt="{artist}">'

        contact_html = ""
        if contact_email or phone:
            contact_html = f'<div style="margin-top:16px;padding:10px;background:#12121a;border-radius:6px;font-size:13px;color:#888">'
            if contact_email:
                contact_html += f'Email: {contact_email}<br>'
            if phone:
                contact_html += f'Phone: {phone}'
            contact_html += '</div>'

        return f"""<!DOCTYPE html>
<html><head><meta charset="utf-8"></head>
<body style="font-family:Arial,sans-serif;background:#0a0a12;color:#e0e0e0;margin:0;padding:20px">
<div style="max-width:600px;margin:0 auto">
<div style="border-bottom:2px solid #00d4ff;padding-bottom:8px;margin-bottom:16px">
<h1 style="margin:0;font-size:22px;color:#fff">{artist}</h1>
<div style="font-size:13px;color:#00d4ff;margin-top:4px">{genre}</div>
</div>
{photo_html}
<div style="font-size:14px;line-height:1.6;color:#ccc">{bio}</div>
{press_html}
<div style="margin-top:16px"><strong style="color:#aaa;font-size:13px">Listen:</strong><br>{links_html}</div>
{contact_html}
<div style="margin-top:20px;padding-top:12px;border-top:1px solid #222;font-size:11px;color:#555;text-align:center">
Electronic Press Kit &mdash; Generated by SoundScape Pilot
</div>
</div></body></html>"""

    def generate_text(self, artist: str, genre: str, bio: str, spotify: str = "",
                      soundcloud: str = "", apple_music: str = "", youtube: str = "",
                      press_quotes: str = "", photo_url: str = "",
                      website: str = "", instagram: str = "", facebook: str = "",
                      twitter: str = "", contact_email: str = "", phone: str = "",
                      email: str = "") -> str:
        contact_email = contact_email or email or ""
        lines = [f"{artist}  |  {genre}", "", bio]
        if press_quotes:
            lines.append("")
            for q in press_quotes.split("\n"):
                q = q.strip()
                if q:
                    lines.append(f'Press: "{q}"')
        links = []
        for label, url in [("Spotify", spotify), ("SoundCloud", soundcloud),
                           ("Apple Music", apple_music), ("YouTube", youtube),
                           ("Website", website), ("Instagram", instagram),
                           ("Facebook", facebook), ("Twitter", twitter)]:
            if url:
                links.append(f"{label}: {url}")
        if links:
            lines.append("")
            lines.append("Links:")
            lines.extend(links)
        if contact_email or phone:
            lines.append("")
            if contact_email:
                lines.append(f"Contact: {contact_email}")
            if phone:
                lines.append(f"Phone: {phone}")
        return "\n".join(lines)


