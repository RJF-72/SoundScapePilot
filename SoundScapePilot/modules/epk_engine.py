    def research(self, station_name: str, contact: str = "", website: str = "") -> Dict[str, Any]:
        key = station_name.lower().strip()
        known = None
        for k, v in self.KNOWN_SUBMISSIONS.items():
            if k in key:
                known = v
                break
        if known:
            return dict(known)

        email = contact or ""
        if not email and website:
            domain = re.sub(r"https?://", "", website).split("/")[0]
            email = f"music@{domain}"

        if website:
            return {
                "method": "website",
                "website": website,
                "format": "digital",
                "notes": f"Visit station website ({website}) for submission guidelines."
            }
        if email:
            return {
                "method": "email",
                "email": email,
                "format": "digital",
                "notes": "Send EPK with streaming links to the station's music director."
            }
        return {
            "method": "unknown",
            "notes": "Research this station's website for submission guidelines."
        }
